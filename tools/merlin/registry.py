"""Launch-profile registry and launcher renderer for the Merlin engine.

Standard library only (Python >= 3.10), no GPU needed. The registry lives in
``tools/merlin/profiles/*.json``:

* ``flash-next.json``: Flash-Next (Qwen3.8-Flash-Next W4A16 Merlin) profiles. Every
  row is a flat record (layout, serving numbers, interconnect environment, capacity
  estimate, evidence, status label). ``fn-quad-3090`` is the one profile that has
  been qualified on the reference host (with the Swift 1.5 and Huihui quads since the 3.0.0 bench
  card). Every other row is labelled "untested / community-validated" until a run says
  otherwise.
* ``qwen38-27b.json`` / ``nemotron-super-vl.json`` / ``ornith.json``: the 27B (1 / 2 / 4 cards), Super VL and Ornith 1.5 rows; their
  ``launch`` block holds the family values ``launch.py`` needs. Their launcher files are shims too.

``render_launcher`` turns a Flash-Next profile into its launcher file: since Merlin 3.0.0 a
short bash shim that execs ``tools/merlin/launch.py --profile <id>`` (the one launcher,
which builds the environment and ``vllm serve`` flags from the profile). The files under
``tools/merlin/launchers/`` and the Swift / Huihui recipe launchers are generated by this
module and a test fails when one is stale.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
PROFILES_DIR = HERE / "profiles"
LAUNCHERS_DIR = HERE / "launchers"

LABEL_TESTED = "tested"
LABEL_UNTESTED = "untested"
LABEL_PARKED = "parked"  # 27B only: a gated profile that is not part of the release
REFERENCE_ID = "fn-quad-3090"

# The only archs the v3 engine line targets: Ampere sm_80 + sm_86, Lovelace sm_89.
SUPPORTED_ARCHS = ("sm_80", "sm_86", "sm_89")
# Archs on which the engine admits fp8_e4m3 KV (qsa.py _validated_qsa_fp8_dtype): sm_86 via the Merlin byte decoder,
# sm_89+ via upstream's native cast. sm_80 is refused.
FP8_KV_ARCHS = frozenset({"sm_86", "sm_89"})
KV_TAG = {"fp8_e4m3": "fp8", "bfloat16": "bf16"}
N_LAYERS = (
    48  # Flash-Next decoder layers (the MTP layer is extra and rides the last stage)
)
MTP_K = 3

# vLLM-style capture-size ladder used by the shipped profile; extended in steps of 16 above 32,
# matching the octo profiles ([.., 32, 40, 48, 64, 80, 96, 112, 128]).
_LADDER = [1, 2, 3, 4, 6, 8, 12, 16, 24, 32, 40, 48, 64, 80, 96, 112, 128]


class ProfileError(ValueError):
    """The registry is malformed or a requested profile does not exist."""


# --------------------------------------------------------------------------------------------
# Loading and validation
# --------------------------------------------------------------------------------------------
def load_registry(
    model: str = "flash-next", profiles_dir: Path | None = None
) -> dict[str, Any]:
    name = {
        "flash-next": "flash-next.json",
        "27b": "qwen38-27b.json",
        "svl": "nemotron-super-vl.json",
        "ornith": "ornith.json",
    }.get(model)
    if name is None:
        raise ProfileError(f"unknown model {model!r} (flash-next, 27b, svl or ornith)")
    path = (profiles_dir or PROFILES_DIR) / name
    with open(path, encoding="utf-8") as f:
        reg = json.load(f)
    problems = validate_registry(reg)
    if problems:
        raise ProfileError(f"{path}: " + "; ".join(problems))
    return reg


def capture_sizes_for(max_num_seqs: int, k: int = MTP_K) -> list[int]:
    """Capture sizes covering ``max_num_seqs * (k + 1)`` decode tokens (the shipped ladder)."""
    top = max_num_seqs * (k + 1)
    sizes = [s for s in _LADDER if s <= top]
    if top not in sizes:
        sizes.append(top)
    return sizes


def vram_class(gib: float) -> int | None:
    """Nominal VRAM class (24/32/40/48/64/80 GiB) of a card, tolerant to ~7 % of reporting slack."""
    for nominal in (24, 32, 40, 48, 64, 80):
        if nominal * 0.93 <= gib <= nominal * 1.07:
            return nominal
    return None


def _check_flash_next_profile(p: dict[str, Any], labels: dict[str, Any]) -> list[str]:
    errs: list[str] = []
    pid = p.get("id", "?")
    for key in (
        "id",
        "title",
        "status",
        "rank",
        "match",
        "layout",
        "serve",
        "interconnect",
        "cuda_visible_devices",
        "warm",
        "capacity",
        "evidence",
        "notes",
    ):
        if key not in p:
            errs.append(f"{pid}: missing {key}")
    if errs:
        return errs
    if p["status"] not in labels:
        errs.append(f"{pid}: status {p['status']!r} is not a known label")
    if "tested_label" in p:
        tl = p["tested_label"]
        if not isinstance(tl, str) or not tl.strip():
            errs.append(f"{pid}: tested_label must be a non-empty string")
        if p["status"] != LABEL_TESTED:
            errs.append(f"{pid}: tested_label is only for status 'tested'")
        if not p["match"].get("tested_gpu_names"):
            errs.append(f"{pid}: tested_label needs match.tested_gpu_names (the cards it was tested on)")
    m, lay, srv, cap = p["match"], p["layout"], p["serve"], p["capacity"]
    cards = m["cards"]
    if lay["tp"] * lay["pp"] != cards:
        errs.append(f"{pid}: tp*pp = {lay['tp'] * lay['pp']} != cards {cards}")
    part = lay.get("partition")
    if lay["pp"] > 1:
        if not part or len(part) != lay["pp"] or sum(part) != N_LAYERS:
            errs.append(
                f"{pid}: partition {part} must have pp={lay['pp']} entries summing to {N_LAYERS}"
            )
    elif part:
        errs.append(f"{pid}: pp=1 but a partition is set")
    if lay["ep"] and lay["tp"] < 2:
        errs.append(f"{pid}: expert parallel needs tp >= 2")
    if len(p["cuda_visible_devices"].split(",")) != cards:
        errs.append(f"{pid}: cuda_visible_devices does not list {cards} GPUs")
    if srv["kv_cache_dtype"] not in ("fp8_e4m3", "bfloat16"):
        errs.append(f"{pid}: kv_cache_dtype {srv['kv_cache_dtype']!r}")
    # Engine gate (qsa.py _validated_qsa_fp8_dtype): fp8_e4m3 KV is admitted on sm_86 (Merlin byte decoder) and
    # sm_89+ (upstream native cast); sm_80 is refused and needs bfloat16.
    if srv["kv_cache_dtype"] == "fp8_e4m3" and not set(m["arch"]) <= FP8_KV_ARCHS:
        errs.append(
            f"{pid}: fp8_e4m3 KV is refused by the engine on {sorted(set(m['arch']) - FP8_KV_ARCHS)}; "
            "the default for a profile that lists such an arch is bfloat16"
        )
    for dtype, alt in srv.get("kv_alt", {}).items():
        if dtype == srv["kv_cache_dtype"] or dtype not in ("fp8_e4m3", "bfloat16"):
            errs.append(f"{pid}: kv_alt dtype {dtype!r} must be the other KV dtype")
            continue
        if not alt.get("archs") or not set(alt["archs"]) <= set(m["arch"]):
            errs.append(f"{pid}: kv_alt {dtype} archs must be a subset of match.arch")
        if dtype == "fp8_e4m3" and not set(alt.get("archs", [])) <= FP8_KV_ARCHS:
            errs.append(f"{pid}: kv_alt fp8_e4m3 listed for an arch the engine refuses")
        if alt.get("capacity", {}).get("estimate") is not True:
            errs.append(f"{pid}: kv_alt {dtype} capacity must be marked estimate")
        if not 1 <= alt.get("max_num_seqs", 0) <= 8:
            errs.append(f"{pid}: kv_alt {dtype} needs max_num_seqs in 1..8")
    if srv["capture_sizes"] != capture_sizes_for(srv["max_num_seqs"]):
        errs.append(
            f"{pid}: capture_sizes do not match the ladder for max_num_seqs={srv['max_num_seqs']}"
        )
    for a in m["arch"]:
        if a not in SUPPORTED_ARCHS:
            errs.append(f"{pid}: arch {a} is not a v3 target")
    ic = p["interconnect"]
    if (
        not ic.get("modes")
        or ic.get("default") not in ic["modes"]
        or set(ic["modes"]) - {"on", "off"}
    ):
        errs.append(
            f"{pid}: interconnect needs modes (on/off) and a default among them"
        )
    if m["p2p"] not in ("on", "off", "any"):
        errs.append(f"{pid}: match.p2p must be on, off or any")
    if m["p2p"] == "on" and "on" not in ic.get("modes", {}):
        errs.append(f"{pid}: matches P2P hosts but has no 'on' interconnect mode")
    if m["p2p"] == "off" and "off" not in ic.get("modes", {}):
        errs.append(f"{pid}: matches non-P2P hosts but has no 'off' interconnect mode")
    if p["warm"] not in (0, 1):
        errs.append(f"{pid}: warm must be 0 or 1")
    if m["arch"] != ["sm_86"] and p["warm"] != 0:
        errs.append(
            f"{pid}: persisted Triton autotune is sm_86 only; warm must be 0 on {m['arch']}"
        )
    if p["status"] == LABEL_UNTESTED and not p["evidence"]:
        errs.append(f"{pid}: untested rows must say what evidence exists (even 'none')")
    if cap.get("estimate") is not True and p["status"] != LABEL_TESTED:
        errs.append(f"{pid}: capacity of an untested row must be marked estimate")
    return errs


def validate_registry(reg: dict[str, Any]) -> list[str]:
    errs: list[str] = []
    for key in ("schema", "model", "labels", "profiles"):
        if key not in reg:
            errs.append(f"missing {key}")
    if errs:
        return errs
    labels = reg["labels"]
    allowed = {LABEL_TESTED, LABEL_UNTESTED} | (
        {LABEL_PARKED} if reg["model"] == "27b" else set()
    )
    if set(labels) != allowed:
        errs.append(
            "labels must be exactly " + " and ".join(repr(a) for a in sorted(allowed))
        )
    for p in reg["profiles"]:
        if p.get("status") not in labels:
            errs.append(
                f"{p.get('id')}: status {p.get('status')!r} is not a known label"
            )
    seen: set[str] = set()
    for p in reg["profiles"]:
        pid = p.get("id")
        if pid in seen:
            errs.append(f"duplicate id {pid}")
        seen.add(pid)
        if reg["model"] == "flash-next":
            errs.extend(_check_flash_next_profile(p, labels))
            checkpoint = p.get("checkpoint")
            if checkpoint:
                entry = reg.get("checkpoints", {}).get(checkpoint)
                if not entry or not all(
                    key in entry
                    for key in (
                        "hf_repo", "scales", "served_names", "reasoning_effort",
                        "draft_vocab_sha256", "checkpoint_marker",
                    )
                ):
                    errs.append(f"{pid}: incomplete checkpoint {checkpoint!r}")
        else:
            for key in (
                "id",
                "title",
                "status",
                "match",
                "launcher",
                "capacity",
                "evidence",
                "notes",
            ):
                if key not in p:
                    errs.append(f"{pid}: missing {key}")
    if reg["model"] == "flash-next" and REFERENCE_ID not in seen:
        errs.append(f"reference profile {REFERENCE_ID} is missing")
    if "launch" not in reg:
        errs.append("missing launch (the family block tools/merlin/launch.py reads)")
    elif reg["model"] == "27b":
        for p in reg["profiles"]:
            if p.get("launch_shape") not in reg["launch"].get("shapes", {}):
                errs.append(f"{p.get('id')}: launch_shape must name one of launch.shapes")
    return errs


def kv_variants(p: dict[str, Any]) -> list[str]:
    """KV dtypes selectable on a profile: the default first, then the sized alternatives."""
    return [p["serve"]["kv_cache_dtype"], *p["serve"].get("kv_alt", {})]


def variant_profile(p: dict[str, Any], dtype: str) -> dict[str, Any]:
    """``p`` with the given KV dtype. The default returns ``p`` itself; an alternative is always
    labelled untested (no run on that KV dtype) and carries its own seqs, capture ladder and capacity."""
    if dtype == p["serve"]["kv_cache_dtype"]:
        return p
    alt = p["serve"].get("kv_alt", {}).get(dtype)
    if alt is None:
        raise ProfileError(
            f"{p['id']} has no {dtype} KV variant; selectable: {', '.join(kv_variants(p))}"
        )
    v = json.loads(json.dumps(p))
    srv = v["serve"]
    srv.pop("kv_alt", None)
    srv["kv_cache_dtype"] = dtype
    srv["max_num_seqs"] = alt["max_num_seqs"]
    srv["capture_sizes"] = capture_sizes_for(alt["max_num_seqs"])
    v["capacity"] = alt["capacity"]
    v["match"]["arch"] = list(alt["archs"])
    v["status"] = LABEL_UNTESTED
    v["variant_of"] = p["id"]
    v["title"] = f"{p['title'].replace(' (the shipped v3.0.0 profile)', '')} [{KV_TAG[dtype]} KV variant]"
    v["evidence"] = [
        f"None for {dtype} KV on this profile: the default variant's evidence ({p['status']}) does not carry over."
    ]
    v["notes"] = [
        f"KV variant of {p['id']}: same layout and pin, KV {dtype}. Selectable, never the tested row; sized by the capacity basis above."
    ] + [
        n
        for n in p["notes"]
        if not n.startswith(("KV default is", "Reference profile", "Design point"))
        and "KV default is" not in n
        and "KV is bfloat16 because" not in n
    ]
    v.pop("acceptance", None)
    return v


def variant_launcher_name(profile_id: str, dtype: str) -> str:
    return "serve-" + re.sub(r"^fn-", "", profile_id) + f"-kv-{KV_TAG[dtype]}.sh"


def get_profile(reg: dict[str, Any], profile_id: str) -> dict[str, Any]:
    for p in reg["profiles"]:
        if p["id"] == profile_id:
            return p
    raise ProfileError(
        f"no profile {profile_id!r}; known: "
        + ", ".join(p["id"] for p in reg["profiles"])
    )


def label_text(reg: dict[str, Any], profile: dict[str, Any], status: str | None = None) -> str:
    """The row's label; a tested row may carry its own wording (`tested_label`, e.g. tested on 4 x CMP 170HX 64 GB)."""
    status = status or profile["status"]
    if status == LABEL_TESTED and profile.get("tested_label"):
        return profile["tested_label"]
    return reg["labels"][status]


def env_str(mode: dict[str, Any]) -> str:
    parts = [f"{k}={v}" for k, v in mode.get("exports", {}).items()]
    parts += [f"unset {v}" for v in mode.get("unset", [])]
    if mode.get("disable_custom_all_reduce"):
        parts.append("--disable-custom-all-reduce")
    return " ".join(parts) or "(none)"


def _default_mode(p: dict[str, Any]) -> dict[str, Any]:
    ic = p["interconnect"]
    return ic["modes"][ic["default"]]


def diff_vs_reference(reg: dict[str, Any], p: dict[str, Any]) -> list[str]:
    """Human-readable list of what differs from the tested reference profile."""
    ref = get_profile(reg, REFERENCE_ID)
    out: list[str] = []

    def cmp(name: str, a: Any, b: Any) -> None:
        if a != b:
            out.append(f"{name}: {a} -> {b}")

    cmp("tensor-parallel-size", ref["layout"]["tp"], p["layout"]["tp"])
    cmp("pipeline-parallel-size", ref["layout"]["pp"], p["layout"]["pp"])
    cmp("expert parallel", ref["layout"]["ep"], p["layout"]["ep"])
    cmp("VLLM_PP_LAYER_PARTITION", ref["layout"]["partition"], p["layout"]["partition"])
    cmp("max-num-seqs", ref["serve"]["max_num_seqs"], p["serve"]["max_num_seqs"])
    cmp(
        "max-num-batched-tokens",
        ref["serve"]["max_num_batched_tokens"],
        p["serve"]["max_num_batched_tokens"],
    )
    cmp("kv-cache-dtype", ref["serve"]["kv_cache_dtype"], p["serve"]["kv_cache_dtype"])
    cmp(
        "kv-cache-memory (bytes per card)",
        ref["serve"]["kv_cache_memory"],
        p["serve"]["kv_cache_memory"],
    )
    if ref["serve"]["capture_sizes"] != p["serve"]["capture_sizes"]:
        out.append(
            f"cudagraph capture sizes: up to {ref['serve']['capture_sizes'][-1]} -> "
            f"up to {p['serve']['capture_sizes'][-1]}"
        )
    cmp(
        "interconnect environment (default mode)",
        env_str(_default_mode(ref)),
        env_str(_default_mode(p)),
    )
    if len(p["interconnect"]["modes"]) > 1:
        out.append(
            "launch-time switch P2P=on|off (default "
            + p["interconnect"]["default"]
            + ")"
        )
    cmp(
        "CUDA_VISIBLE_DEVICES default",
        ref["cuda_visible_devices"],
        p["cuda_visible_devices"],
    )
    cmp("WARM (persisted Triton autotune, sm_86 only)", ref["warm"], p["warm"])
    if p.get("checkpoint"):
        checkpoint = reg["checkpoints"][p["checkpoint"]]
        out.append("checkpoint: " + checkpoint["hf_repo"])
        out.append("KV scale sidecar: " + checkpoint["scales"])
        cmp("served names", reg["base"]["served_names"], checkpoint["served_names"])
        cmp("default reasoning effort", REASONING_EFFORT_DEFAULT, checkpoint["reasoning_effort"])
        out.append(f"Full-vocabulary MTP head (DRAFT_HEAD sets its precision; default {DRAFT_HEAD_DEFAULT}); no reduced draft table ships or is qualified (REDUCED_DRAFT_VOCAB=1 is refused).")
    return out


# --------------------------------------------------------------------------------------------
# Launcher rendering: every launcher file is a shim for tools/merlin/launch.py (the one launcher)
# --------------------------------------------------------------------------------------------
# The shipped draft-head precision for every Flash-Next launcher: one constant, one-line change (bf16 | int8 | int4).
DRAFT_HEAD_DEFAULT = "bf16"
# The served default reasoning effort of vanilla Flash-Next. The Swift / Huihui checkpoint rows (flash-next.json) and the 27B /
# ThinkingCap `thinking` strings (qwen38-27b.json) carry the same value; keep all five profiles equal to this constant.
# A request still picks its own (`chat_template_kwargs.reasoning_effort`).
REASONING_EFFORT_DEFAULT = "medium"

SHIM_MAX_LINES = 10


def launcher_name(profile_id: str) -> str:
    return "serve-" + re.sub(r"^fn-", "", profile_id) + ".sh"


def render_shim(profile_id: str, kv: str | None = None, checkpoint: str | None = None,
                generate: str | None = None, usage: str | None = None) -> str:
    """A <= SHIM_MAX_LINES bash shim that execs tools/merlin/launch.py for one profile.

    The shim finds the checkout from its own directory upwards (the first directory holding tools/merlin/launch.py),
    so ``--emit launcher`` output works wherever it is saved inside the tree. MERLIN_HOME overrides the checkout;
    MERLIN_PYTHON the interpreter.
    """
    flags = f"--profile {profile_id}" + (f" --kv {kv}" if kv else "") + (f" --checkpoint {checkpoint}" if checkpoint else "")
    lines = ["#!/usr/bin/env bash"]
    if generate:
        lines.append(f"# GENERATED by `{generate}`: shim for the one launcher, tools/merlin/launch.py {flags}; do not edit by hand.")
    else:
        lines.append(f"# Merlin 3.0.0: shim for the one launcher, tools/merlin/launch.py {flags}.")
    if usage:
        lines.append(f"#   {usage}")
    lines += [
        "set -euo pipefail",
        'REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"',
        'until [ -f "$REPO/tools/merlin/launch.py" ] || [ "$REPO" = / ]; do REPO="$(dirname "$REPO")"; done',
        'REPO="${MERLIN_HOME:-$REPO}"',
        '[ -f "$REPO/tools/merlin/launch.py" ] || { echo "no tools/merlin/launch.py above ${BASH_SOURCE[0]}; set MERLIN_HOME" >&2; exit 2; }',
        f'exec "${{MERLIN_PYTHON:-python3}}" "$REPO/tools/merlin/launch.py" {flags} -- "$@"',
    ]
    assert len(lines) <= SHIM_MAX_LINES
    return "\n".join(lines) + "\n"


def render_launcher(reg: dict[str, Any], p: dict[str, Any]) -> str:
    """Render ``p``'s launcher file: a shim (LF endings, ends with a newline)."""
    if reg["model"] != "flash-next":
        raise ProfileError(
            "only Flash-Next profiles are rendered; 27B and Super VL entries point at the shims under models/"
        )
    variant = p.get("variant_of")
    pid = variant or p["id"]
    kv = KV_TAG[p["serve"]["kv_cache_dtype"]] if variant else None
    recipe = p.get("recipe_launcher")
    gen = f"python tools/merlin/preflight.py --emit launcher --profile {pid}" + (f" --kv {kv}" if kv else "")
    if recipe:
        ck = reg["checkpoints"][p["checkpoint"]]["hf_repo"].split("/")[-1]
        return render_shim(pid, kv, p["checkpoint"], gen + f" > {recipe}",
                           f"bash {recipe} /path/to/{ck} [extra vllm args]")
    name = variant_launcher_name(variant, p["serve"]["kv_cache_dtype"]) if variant else launcher_name(p["id"])
    return render_shim(pid, kv, p.get("checkpoint"), gen + f" > tools/merlin/launchers/{name}",
                       f"bash tools/merlin/launchers/{name} /path/to/checkpoint [extra vllm args]   ({label_text(reg, p)})")


def render_all(reg: dict[str, Any], ids: list[str] | None = None) -> dict[str, str]:
    """``{file name: text}`` for the given profile ids (default: the checked-in launcher set)."""
    ids = ids or reg.get("launchers", [])
    out = {launcher_name(i): render_launcher(reg, get_profile(reg, i)) for i in ids}
    # every sized KV alternative of a listed profile gets its own generated launcher (default stays the plain name)
    for i in ids:
        p = get_profile(reg, i)
        for dtype in p["serve"].get("kv_alt", {}):
            out[variant_launcher_name(i, dtype)] = render_launcher(reg, variant_profile(p, dtype))
    return out
